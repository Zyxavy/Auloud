"""D-187: the CPU-only helper variant drops the CUDA stack from the export.

The packaging scripts are not covered by the UI tests, so the two functions
that decide what lands in a bundle are tested directly: the requirement-block
parser (hash lines are continuations, so a naive line filter would leave them
behind and break the hash-checked install) and the CPU wheel pin, which is
fetched from PyPI because the lock only carries that wheel off Windows.
"""

from __future__ import annotations

import importlib.util
import io
import json
import subprocess
import sys
from pathlib import Path

import pytest

DEV = Path(__file__).resolve().parents[1] / "dev"
_spec = importlib.util.spec_from_file_location("package_helper", DEV / "package_helper.py")
package_helper = importlib.util.module_from_spec(_spec)
sys.modules["package_helper"] = package_helper
assert _spec.loader is not None
_spec.loader.exec_module(package_helper)

#: A slice of a real `uv export`, including the shapes that break line filters.
EXPORT = """\
# This file is autogenerated by uv
kokoro-onnx==0.6.1 \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via -r requirements.in
nvidia-cudnn-cu12==9.27.0.42 ; sys_platform == 'win32' \\
    --hash=sha256:cccc
    # via auloud-scribe
onnxruntime==1.30.0 ; sys_platform != 'win32' \\
    --hash=sha256:dddd
onnxruntime-gpu==1.29.0 ; sys_platform == 'win32' \\
    --hash=sha256:eeee
    # via auloud-scribe
uvicorn>=0.30.0 \\
    --hash=sha256:ffff
"""


def test_requirement_name_reads_every_export_shape() -> None:
    assert package_helper.requirement_name("onnxruntime-gpu==1.29.0 ; sys_platform == 'x'") == (
        "onnxruntime-gpu"
    )
    assert package_helper.requirement_name("uvicorn>=0.30.0 \\") == "uvicorn"
    assert package_helper.requirement_name("pkg[extra]") == "pkg"
    # Comments and option lines are their own blocks and never match a name.
    assert package_helper.requirement_name("# comment") == "#"
    assert package_helper.requirement_name("--index-url https://example/simple") == "--index-url"


def test_drop_requirements_removes_whole_blocks(tmp_path: Path) -> None:
    target = tmp_path / "requirements.txt"
    target.write_text(EXPORT, encoding="utf-8")

    package_helper.drop_requirements(target, package_helper.GPU_PACKAGES)

    text = target.read_text(encoding="utf-8")
    assert "onnxruntime-gpu" not in text
    assert "nvidia-cudnn-cu12" not in text
    # The hash lines and the "# via" comment of a dropped block go with it.
    assert "cccc" not in text
    assert "eeee" not in text
    # Everything else survives intact, hashes included.
    assert "kokoro-onnx==0.6.1" in text and "aaaa" in text and "bbbb" in text
    assert "onnxruntime==1.30.0 ; sys_platform != 'win32'" in text
    assert "uvicorn>=0.30.0" in text and "ffff" in text

    # The CPU variant drops that non-Windows entry too, so the marker-false
    # requirement cannot cancel the hashed CPU wheel added in its place.
    package_helper.drop_requirements(target, package_helper.GPU_PACKAGES | {"onnxruntime"})
    cpu_text = target.read_text(encoding="utf-8")
    assert "onnxruntime" not in cpu_text
    assert "kokoro-onnx==0.6.1" in cpu_text


def test_locked_version_comes_from_the_lock() -> None:
    locked = package_helper.locked_version("onnxruntime")
    assert locked[0].isdigit()
    with pytest.raises(RuntimeError, match="not in uv.lock"):
        package_helper.locked_version("definitely-not-a-package")


def test_cpu_requirement_is_hash_pinned(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    version = package_helper.locked_version("onnxruntime")
    major, minor = package_helper.PYTHON_VERSION.split(".")[:2]
    tag = f"cp{major}{minor}-cp{major}{minor}-win_amd64.whl"
    payload = {
        "urls": [
            # Another wheel for another Python, to prove the tag decides.
            {"filename": "onnxruntime-0.0.0-cp311-cp311-win_amd64.whl", "digests": {"sha256": "x"}},
            {"filename": f"onnxruntime-{version}-{tag}", "digests": {"sha256": "deadbeef"}},
        ]
    }
    monkeypatch.setattr(
        package_helper.urllib.request,
        "urlopen",
        lambda url: io.BytesIO(json.dumps(payload).encode("utf-8")),
    )

    requirement = package_helper.cpu_onnxruntime_requirement(tmp_path)

    expected = f"onnxruntime=={version} --hash=sha256:deadbeef\n"
    assert requirement.read_text(encoding="utf-8") == expected


def test_cpu_requirement_fails_when_pypi_has_no_matching_wheel(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(
        package_helper.urllib.request,
        "urlopen",
        lambda url: io.BytesIO(json.dumps({"urls": []}).encode("utf-8")),
    )

    with pytest.raises(RuntimeError, match="no cp"):
        package_helper.cpu_onnxruntime_requirement(tmp_path)


def _dist_info(site_packages: Path, *names: str) -> None:
    for name in names:
        (site_packages / name).mkdir(parents=True, exist_ok=True)


def test_install_keeps_project_config_out_and_pins_the_variant(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls: list[list[str]] = []

    def fake_run(command, **kwargs):
        calls.append([str(part) for part in command])
        return subprocess.CompletedProcess(command, 0, "", "")

    monkeypatch.setattr(package_helper.subprocess, "run", fake_run)
    python_exe = tmp_path / "python.exe"
    requirements = tmp_path / "requirements.txt"
    wheel = tmp_path / "auloud_scribe.whl"

    package_helper.install_packages(
        python_exe,
        requirements,
        wheel,
        variant="cpu",
        cpu_requirement=tmp_path / "onnxruntime-cpu.txt",
    )
    package_helper.install_packages(
        python_exe, requirements, wheel, variant="gpu", cpu_requirement=None
    )

    installs = [call for call in calls if "install" in call]
    assert len(installs) == 4
    # Without --no-config the project's override rewrites the CPU requirement
    # to a false marker and the install silently does nothing.
    assert all("--no-config" in call for call in installs)
    assert "--require-hashes" in installs[0]
    assert str(tmp_path / "onnxruntime-cpu.txt") in installs[0]
    assert package_helper.ORT_CUDA_FEED in installs[2]
    # Without the strategy the feed answers for names it merely carries, so the
    # locked versions of unrelated packages cannot be resolved.
    assert "unsafe-best-match" in installs[2]
    assert "unsafe-best-match" not in installs[0]
    # Every call takes the lock as final. Without it the wheel's metadata
    # resolves the CUDA stack itself, and the main install turns a pinned name
    # into an unpinned requirement that hash mode then rejects.
    assert all("--no-deps" in call for call in installs)


def test_helper_runs_check_uses_the_flat_import_shim(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls: list[list[str]] = []

    def fake_run(command, **kwargs):
        calls.append([str(part) for part in command])
        return subprocess.CompletedProcess(command, 0, "imports ok\n", "")

    monkeypatch.setattr(package_helper.subprocess, "run", fake_run)
    site_packages = tmp_path / "site-packages"
    package_helper.assert_helper_runs(tmp_path / "python.exe", site_packages)

    assert "-c" in calls[0]
    # The shim points at the namespace package, not at site-packages itself.
    assert calls[0][-1] == str(site_packages / "scribe")

    monkeypatch.setattr(
        package_helper.subprocess,
        "run",
        lambda command, **kwargs: subprocess.CompletedProcess(
            command, 1, "", "ModuleNotFoundError: No module named 'tts'"
        ),
    )
    with pytest.raises(RuntimeError, match="cannot import its own code"):
        package_helper.assert_helper_runs(tmp_path / "python.exe", site_packages)


def test_assert_variant_install_stops_a_cpu_bundle_holding_the_cuda_stack(
    tmp_path: Path,
) -> None:
    site_packages = tmp_path / "site-packages"
    _dist_info(site_packages, "onnxruntime-1.30.0.dist-info")
    package_helper.assert_variant_install(site_packages, "cpu")

    _dist_info(site_packages, "onnxruntime_gpu-1.29.0.dist-info", "nvidia_cudnn_cu12-1.dist-info")
    with pytest.raises(RuntimeError, match="unexpected"):
        package_helper.assert_variant_install(site_packages, "cpu")


def test_assert_variant_install_stops_a_gpu_bundle_without_the_gpu_wheel(
    tmp_path: Path,
) -> None:
    site_packages = tmp_path / "site-packages"
    _dist_info(site_packages, "onnxruntime-1.30.0.dist-info")
    with pytest.raises(RuntimeError, match="missing"):
        package_helper.assert_variant_install(site_packages, "gpu")

    _dist_info(site_packages, "onnxruntime_gpu-1.29.0.dist-info")
    package_helper.assert_variant_install(site_packages, "gpu")
